import type { CatalogEntry, PluginType } from './types'

const C = 'PSP 25th Anniversary Bundle'

function psp(
  id: string,
  name: string,
  types: PluginType[],
  summary: string,
  sonicCharacter: string,
  bestFor: string,
  useCases: string[],
  tags: string[] = [],
): CatalogEntry {
  return {
    id,
    name,
    vendor: 'PSP Audioware',
    kind: 'plugin',
    types,
    collections: [C],
    summary,
    sonicCharacter,
    bestFor,
    useCases,
    notes: 'Included in PSP 25th Anniversary Bundle (NFR licenses; sold as a complete package).',
    tags: ['psp-audioware', 'psp-25th-anniversary', ...tags],
  }
}

